const cache = new Map();
let mat = null;
export function weaponMaterial() {
  return mat || (mat = new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.48, metalness: 0.5 }));
}

/** Géométrie + points d'attache d'une arme pour une peinture donnée (mis en cache). */
export function weaponModel(id, skin = 'standard') {
  const key = id + '|' + skin;
  let m = cache.get(key);
  if (!m) {
    const P = getItem('wskin', skin).pal, g = new Geo();
    const B = (w, h, d, x, y, z, c, rx) => g.box(w, h, d, x, y, z, c, rx ? [rx, 0, 0] : null);
    const T = (r, len, x, y, z, c, r2, seg) => g.tube(r, r2 ?? r, len, x, y, z, c, seg || 10);
    const info = (MODELS[id] || MODELS.p9)(g, P, B, T);
    m = { geo: g.build(), muzzle: new THREE.Vector3(...info.muzzle), left: new THREE.Vector3(...info.left) };
    cache.set(key, m);
  }
  return m;
}

export function weaponMesh(id, skin) {
  const m = weaponModel(id, skin), mesh = new THREE.Mesh(m.geo, weaponMaterial());
  mesh.castShadow = true;
  mesh.userData.model = m;
  return mesh;
}
